//! Tiny 3×5 bitmap font (digits, letters, a few signs) for overlay labels, drawn at 2× scale.

const GLYPHS: &[(char, [u8; 5])] = &[
    ('0', [7, 5, 5, 5, 7]), ('1', [2, 6, 2, 2, 7]), ('2', [7, 1, 7, 4, 7]), ('3', [7, 1, 3, 1, 7]),
    ('4', [5, 5, 7, 1, 1]), ('5', [7, 4, 7, 1, 7]), ('6', [7, 4, 7, 5, 7]), ('7', [7, 1, 1, 2, 2]),
    ('8', [7, 5, 7, 5, 7]), ('9', [7, 5, 7, 1, 7]), ('A', [2, 5, 7, 5, 5]), ('B', [6, 5, 6, 5, 6]),
    ('C', [3, 4, 4, 4, 3]), ('D', [6, 5, 5, 5, 6]), ('E', [7, 4, 6, 4, 7]), ('F', [7, 4, 6, 4, 4]),
    ('G', [3, 4, 5, 5, 3]), ('H', [5, 5, 7, 5, 5]), ('I', [7, 2, 2, 2, 7]), ('J', [1, 1, 1, 5, 2]),
    ('K', [5, 5, 6, 5, 5]), ('L', [4, 4, 4, 4, 7]), ('M', [5, 7, 7, 5, 5]), ('N', [6, 5, 5, 5, 5]),
    ('O', [2, 5, 5, 5, 2]), ('P', [6, 5, 6, 4, 4]), ('Q', [2, 5, 5, 6, 3]), ('R', [6, 5, 6, 5, 5]),
    ('S', [3, 4, 2, 1, 6]), ('T', [7, 2, 2, 2, 2]), ('U', [5, 5, 5, 5, 7]), ('V', [5, 5, 5, 5, 2]),
    ('W', [5, 5, 7, 7, 5]), ('X', [5, 5, 2, 5, 5]), ('Y', [5, 5, 2, 2, 2]), ('Z', [7, 1, 2, 4, 7]),
    ('-', [0, 0, 7, 0, 0]), (':', [0, 2, 0, 2, 0]), ('.', [0, 0, 0, 0, 2]), ('/', [1, 1, 2, 4, 4]),
    ('>', [4, 2, 1, 2, 4]), ('<', [1, 2, 4, 2, 1]), ('#', [5, 7, 5, 7, 5]), ('(', [1, 2, 2, 2, 1]),
    (')', [4, 2, 2, 2, 4]), ('=', [0, 7, 0, 7, 0]), ('+', [0, 2, 7, 2, 0]), (',', [0, 0, 0, 2, 4]),
];

/// Draw `s` at (x, y) in colour `c` into a 640×480 RGB24 buffer; returns the x after the text.
pub fn text(fb: &mut [u8], mut x: i32, y: i32, s: &str, c: [u8; 3]) -> i32 {
    for ch in s.chars() {
        let ch = ch.to_ascii_uppercase();
        if let Some((_, g)) = GLYPHS.iter().find(|(k, _)| *k == ch) {
            for (row, bits) in g.iter().enumerate() {
                for col in 0..3 {
                    if bits & (4 >> col) != 0 {
                        let (px, py) = (x + col * 2, y + row as i32 * 2);
                        super::fill(fb, px, py, px + 2, py + 2, c);
                    }
                }
            }
        }
        x += 8;
    }
    x
}
